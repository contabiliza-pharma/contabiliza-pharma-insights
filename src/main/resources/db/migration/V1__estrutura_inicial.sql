-- Diferenças em relação ao DBML (todas exigidas pelo Guia de Desenvolvimento):
--   * coluna "versao" em empresa, estabelecimento e usuario (lock otimista, §6.15)
--   * CHECKs de competência no 1º dia do mês e de CNPJ só com dígitos (§6.5)
--   * tabela chave_idempotencia (Idempotency-Key, §6.14)
--   * tabela pendencia_importacao não existe: alertas ficam em importacao.alertas (DBML)
-- =====================================================================

-- ---------- Enums ----------
CREATE TYPE regime_tributario   AS ENUM ('simples', 'presumido', 'real');
CREATE TYPE perfil_usuario      AS ENUM ('cliente', 'colaborador', 'administrador');
CREATE TYPE tipo_importacao     AS ENUM ('sped', 'pgdas', 'folha', 'encargos');
CREATE TYPE status_importacao   AS ENUM ('processando', 'concluida', 'com_alerta', 'erro');
CREATE TYPE grupo_cfop          AS ENUM ('venda', 'devolucao', 'outros');
CREATE TYPE indicador_operacao  AS ENUM ('entrada', 'saida');   -- IND_OPER 0/1 do C100
CREATE TYPE tipo_trabalhador    AS ENUM ('empregado', 'contribuinte', 'estagiario');
CREATE TYPE tipo_evento         AS ENUM ('provento', 'desconto', 'informativo');

-- ---------- Cadastro e acesso ----------
CREATE TABLE empresa (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raiz_cnpj     char(8)      NOT NULL UNIQUE CHECK (raiz_cnpj ~ '^[0-9]{8}$'),
    razao_social  varchar(150) NOT NULL,
    regime        regime_tributario,
    ativa         boolean      NOT NULL DEFAULT true,
    criado_em     timestamp    NOT NULL DEFAULT now(),
    versao        integer      NOT NULL DEFAULT 0
);

CREATE TABLE estabelecimento (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      integer      NOT NULL REFERENCES empresa (id),
    cnpj            char(14)     NOT NULL UNIQUE CHECK (cnpj ~ '^[0-9]{14}$'),
    nome            varchar(150),
    ie              varchar(14),
    uf              char(2),
    codigo_dominio  integer UNIQUE,                       -- codi_emp / cp_codi_emp do Domínio
    matriz          boolean      NOT NULL DEFAULT false,
    ativo           boolean      NOT NULL DEFAULT true,
    versao          integer      NOT NULL DEFAULT 0
);
CREATE INDEX ix_estabelecimento_empresa ON estabelecimento (empresa_id);

CREATE TABLE usuario (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               varchar(150)   NOT NULL,
    email              varchar(150)   NOT NULL UNIQUE,
    senha_hash         varchar(255)   NOT NULL,          -- Argon2id (PHC string); nunca texto puro
    perfil             perfil_usuario NOT NULL,
    empresa_id         integer REFERENCES empresa (id),
    senha_temporaria   boolean        NOT NULL DEFAULT true,
    senha_expira_em    timestamp,                        -- 48 h após criação ou redefinição
    tentativas_falhas  smallint       NOT NULL DEFAULT 0,
    bloqueado_ate      timestamp,
    ativo              boolean        NOT NULL DEFAULT true,
    ultimo_acesso      timestamp,
    criado_em          timestamp      NOT NULL DEFAULT now(),
    versao             integer        NOT NULL DEFAULT 0,
    -- cliente precisa de empresa; colaborador e administrador não têm
    CONSTRAINT ck_usuario_empresa_por_perfil CHECK (
        (perfil = 'cliente' AND empresa_id IS NOT NULL) OR
        (perfil <> 'cliente' AND empresa_id IS NULL)
    ),
    CONSTRAINT ck_usuario_email_minusculo CHECK (email = lower(email))
);

CREATE TABLE log_acao (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  integer REFERENCES usuario (id),
    acao        varchar(50)  NOT NULL,
    alvo        varchar(150),
    ip          varchar(45),
    criado_em   timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX ix_log_acao_usuario_data ON log_acao (usuario_id, criado_em);

CREATE TABLE chave_idempotencia (
    chave            uuid PRIMARY KEY,
    usuario_id       integer      NOT NULL REFERENCES usuario (id),
    rota             varchar(150) NOT NULL,
    resposta_status  smallint     NOT NULL,
    resposta_corpo   text         NOT NULL,
    criado_em        timestamp    NOT NULL DEFAULT now()
);

-- ---------- Controle de importação ----------
CREATE TABLE importacao (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                tipo_importacao   NOT NULL,
    arquivo_nome        varchar(255)      NOT NULL,
    hash                char(64)          NOT NULL UNIQUE,   -- SHA-256 do arquivo
    estabelecimento_id  integer REFERENCES estabelecimento (id),
    competencia         date CHECK (competencia = date_trunc('month', competencia)::date),
    status              status_importacao NOT NULL DEFAULT 'processando',
    alertas             text,
    importado_por       integer           NOT NULL REFERENCES usuario (id),
    importado_em        timestamp         NOT NULL DEFAULT now()
);
CREATE INDEX ix_importacao_data ON importacao (importado_em DESC);

-- ---------- Dados fiscais (SPED e PGDAS-D) ----------
CREATE TABLE cfop (
    codigo     char(4)      PRIMARY KEY CHECK (codigo ~ '^[0-9]{4}$'),
    descricao  varchar(255) NOT NULL,
    grupo      grupo_cfop   NOT NULL
);

CREATE TABLE sped_arquivo (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id       integer  NOT NULL UNIQUE REFERENCES importacao (id),
    estabelecimento_id  integer  NOT NULL REFERENCES estabelecimento (id),
    competencia         date     NOT NULL CHECK (competencia = date_trunc('month', competencia)::date),
    dt_ini              date     NOT NULL,
    dt_fin              date     NOT NULL,
    cod_fin             smallint NOT NULL CHECK (cod_fin IN (0, 1)),   -- 0 original; 1 substituto
    cod_ver             char(3),
    ind_perfil          char(1),
    vigente             boolean  NOT NULL DEFAULT true
);
CREATE INDEX ix_sped_estab_comp ON sped_arquivo (estabelecimento_id, competencia);
-- só um SPED vigente por estabelecimento e competência
CREATE UNIQUE INDEX ux_sped_vigente ON sped_arquivo (estabelecimento_id, competencia) WHERE vigente;

CREATE TABLE icms_analitico (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sped_arquivo_id  integer            NOT NULL REFERENCES sped_arquivo (id) ON DELETE CASCADE,
    ind_oper         indicador_operacao NOT NULL,
    cst              char(3)            NOT NULL,
    cfop             char(4)            NOT NULL REFERENCES cfop (codigo),
    aliquota         numeric(6,2),
    vl_opr           numeric(15,2)      NOT NULL,   -- C190 campo 05
    vl_bc_icms       numeric(15,2)      NOT NULL,
    vl_icms          numeric(15,2)      NOT NULL
);
CREATE UNIQUE INDEX ux_icms_analitico ON icms_analitico
    (sped_arquivo_id, ind_oper, cst, cfop, COALESCE(aliquota, -1));

CREATE TABLE icms_apuracao (
    sped_arquivo_id           integer PRIMARY KEY REFERENCES sped_arquivo (id) ON DELETE CASCADE,
    debitos                   numeric(15,2) NOT NULL,  -- VL_TOT_DEBITOS
    ajustes_debito_doc        numeric(15,2) NOT NULL,  -- VL_AJ_DEBITOS
    ajustes_debito            numeric(15,2) NOT NULL,  -- VL_TOT_AJ_DEBITOS
    estornos_credito          numeric(15,2) NOT NULL,  -- VL_ESTORNOS_CRED
    creditos                  numeric(15,2) NOT NULL,  -- VL_TOT_CREDITOS
    ajustes_credito_doc       numeric(15,2) NOT NULL,  -- VL_AJ_CREDITOS
    ajustes_credito           numeric(15,2) NOT NULL,  -- VL_TOT_AJ_CREDITOS
    estornos_debito           numeric(15,2) NOT NULL,  -- VL_ESTORNOS_DEB
    saldo_credor_anterior     numeric(15,2) NOT NULL,  -- VL_SLD_CREDOR_ANT
    saldo_devedor             numeric(15,2) NOT NULL,  -- VL_SLD_APURADO
    deducoes                  numeric(15,2) NOT NULL,  -- VL_TOT_DED
    icms_recolher             numeric(15,2) NOT NULL,  -- VL_ICMS_RECOLHER
    saldo_credor_transportar  numeric(15,2) NOT NULL,  -- VL_SLD_CREDOR_TRANSPORTAR
    deb_especiais             numeric(15,2) NOT NULL   -- DEB_ESP
);

CREATE TABLE icms_ajuste (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sped_arquivo_id  integer       NOT NULL REFERENCES sped_arquivo (id) ON DELETE CASCADE,
    cod_aj_apur      char(8)       NOT NULL,
    descricao        text,
    valor            numeric(15,2) NOT NULL
);

CREATE TABLE icms_obrigacao (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sped_arquivo_id  integer       NOT NULL REFERENCES sped_arquivo (id) ON DELETE CASCADE,
    cod_or           char(3)       NOT NULL,
    valor            numeric(15,2) NOT NULL,
    vencimento       date          NOT NULL,   -- DT_VCTO
    cod_receita      varchar(20)   NOT NULL,
    mes_ref          date
);

CREATE TABLE receita_pgdas (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id  integer       NOT NULL REFERENCES estabelecimento (id),
    importacao_id       integer       NOT NULL REFERENCES importacao (id),
    competencia         date          NOT NULL CHECK (competencia = date_trunc('month', competencia)::date),
    receita_bruta       numeric(15,2) NOT NULL,
    UNIQUE (estabelecimento_id, competencia)
);

-- ---------- Folha e encargos (Domínio Folha) ----------
-- LGPD: não guardar dados bancários, chave PIX, data de nascimento e matrícula INSS
CREATE TABLE empregado (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id  integer          NOT NULL REFERENCES estabelecimento (id),
    codigo_dominio      integer          NOT NULL,
    nome                varchar(150)     NOT NULL,
    cargo               varchar(100),
    cbo                 varchar(6),
    admissao            date,
    categoria           varchar(10),
    vinculo             varchar(10),
    tipo                tipo_trabalhador NOT NULL,
    UNIQUE (estabelecimento_id, tipo, codigo_dominio)
);

CREATE TABLE evento_folha (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id  integer      NOT NULL REFERENCES estabelecimento (id),
    codigo              integer      NOT NULL,
    nome                varchar(100) NOT NULL,
    tipo                tipo_evento  NOT NULL,
    classificacao       varchar(10),
    UNIQUE (estabelecimento_id, codigo)
);

CREATE TABLE folha_calculo (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empregado_id    integer       NOT NULL REFERENCES empregado (id),
    importacao_id   integer       NOT NULL REFERENCES importacao (id),
    competencia     date          NOT NULL CHECK (competencia = date_trunc('month', competencia)::date),
    tipo_processo   smallint      NOT NULL,
    calculo         integer,
    complemento     integer       NOT NULL DEFAULT 0,
    data_pagto      date,
    salario_base    numeric(15,2),
    base_inss       numeric(15,2),
    base_irrf       numeric(15,2),
    base_fgts       numeric(15,2),
    valor_fgts      numeric(15,2),
    taxa_irrf       numeric(6,2),
    situacao        varchar(20),
    centro_custo    varchar(100),
    departamento    integer,
    UNIQUE (empregado_id, competencia, tipo_processo, complemento)
);
CREATE INDEX ix_folha_calculo_comp ON folha_calculo (competencia);

CREATE TABLE folha_lancamento (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folha_calculo_id  bigint        NOT NULL REFERENCES folha_calculo (id) ON DELETE CASCADE,
    evento_id         integer       NOT NULL REFERENCES evento_folha (id),
    referencia        numeric(12,4),
    tipo_referencia   varchar(10),
    valor             numeric(15,2) NOT NULL,
    compoe_liquido    boolean       NOT NULL DEFAULT true,
    UNIQUE (folha_calculo_id, evento_id)
);

CREATE TABLE encargo_empregado (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estabelecimento_id  integer       NOT NULL REFERENCES estabelecimento (id),
    empregado_id        integer       NOT NULL REFERENCES empregado (id),
    importacao_id       integer       NOT NULL REFERENCES importacao (id),
    competencia         date          NOT NULL CHECK (competencia = date_trunc('month', competencia)::date),
    tipo_processo       smallint      NOT NULL,
    complemento         integer       NOT NULL DEFAULT 0,
    remuneracao         numeric(15,2) NOT NULL,
    fgts                numeric(15,2) NOT NULL,
    fgts_grrf           numeric(15,2) NOT NULL,
    inss_empresa        numeric(15,2) NOT NULL,
    inss_terceiros      numeric(15,2) NOT NULL,
    rat                 numeric(15,2) NOT NULL,
    gilrat              numeric(15,2) NOT NULL,
    deducoes            numeric(15,2) NOT NULL,
    pis                 numeric(15,2) NOT NULL,
    total               numeric(15,2) NOT NULL,
    UNIQUE (empregado_id, competencia, tipo_processo, complemento)
);
CREATE INDEX ix_encargo_estab_comp ON encargo_empregado (estabelecimento_id, competencia);
